window.obterListaAlunos = function() {
    try {
        const salvos = localStorage.getItem('kihap_espetaculo_alunos');
        if (salvos) {
            const parsed = JSON.parse(salvos);
            if (Array.isArray(parsed) && parsed.length > 0) return parsed;
        }
    } catch (e) {
        console.warn('Erro ao carregar alunos do localStorage:', e);
    }
    return JSON.parse(JSON.stringify(window.KIHAP_ALUNOS_PADRAO));
};

window.salvarListaAlunos = function(lista) {
    try {
        localStorage.setItem('kihap_espetaculo_alunos', JSON.stringify(lista));
        return true;
    } catch (e) {
        console.error('Erro ao salvar alunos:', e);
        return false;
    }
};
